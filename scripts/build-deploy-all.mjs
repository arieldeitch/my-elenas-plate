/**
 * Regenerates supabase/deploy_all.sql — the combined, idempotent bundle of EVERY
 * migration in ledger order, for a FRESH project only. Production has its own
 * apply scripts (supabase/DEPLOY.md); pasting this bundle on production would
 * re-run history. Run after adding a migration:  node scripts/build-deploy-all.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "supabase/migrations";
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort();
const parts = [
  `-- Combined, idempotent deploy of all Nutrition Tracker migrations (${files.length} files),
-- for a FRESH Supabase project. Generated by scripts/build-deploy-all.mjs from
-- supabase/migrations/*.sql — do not edit by hand; regenerate after adding a migration.
--
-- PRODUCTION (rqgoiuztphkcvbwtbxbj) MUST NOT run this file: its ledger and data are
-- managed through the per-release scripts in supabase/DEPLOY.md
-- (apply_m1_grants_production.sql, apply_anonymous_join_production.sql,
-- apply_hardening_post_pilot.sql). Never a plain \`supabase db push\` there either.
`,
];
for (const f of files) {
  parts.push(
    `\n-- ${"=".repeat(72)}\n-- ${dir}/${f}\n-- ${"=".repeat(72)}\n${readFileSync(join(dir, f), "utf8").trimEnd()}\n`,
  );
}
writeFileSync("supabase/deploy_all.sql", parts.join(""));
console.log(`deploy_all.sql: ${files.length} migrations`);
